    inline vk::DeviceAddress getBufferAddress(
        const VulkanCore &vkCore, 
        const VulkanBuffer &buffer) {

        return vkCore.device().getBufferAddress(
            vk::BufferDeviceAddressInfo().setBuffer(*(buffer.buffer())));
    };


